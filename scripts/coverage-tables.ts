/**
 * Generate docs/coverage.md: one table per instruction set listing every
 * implemented instruction and accepted pseudoinstruction or alias, the stages
 * implemented for it, whether the compiler emits it, and how many instances
 * were checked against the reference assembler and the reference emulator in
 * the last validation run (src/app/data/support-matrix.json, written by
 * scripts/summarize-validation.ts).
 *
 *   node scripts/coverage-tables.ts [--check]
 *
 * With --check, nothing is written; the process exits with 1 when
 * docs/coverage.md differs (line endings aside) from the tables it would write.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { availableBackends } from '../src/core/target/index.ts';
import { repoRoot } from './lib/corpus.ts';

const root = repoRoot();
const matrix = JSON.parse(readFileSync(join(root, 'src', 'app', 'data', 'support-matrix.json'), 'utf8')) as {
  generated: string;
  source: string;
  targets: Record<string, Record<string, { compilerGenerates: boolean; assemblerChecked: number; emulatorChecked: number }>>;
};
const yes = (b: boolean): string => (b ? 'yes' : 'no');
const lines: string[] = [];
const P = (s = ''): void => {
  lines.push(s);
};
P('# Instruction coverage');
P();
P('This file is generated by `node scripts/coverage-tables.ts` from the instruction catalogs and the results of the last validation run. Do not edit it by hand.');
P();
P('Columns: the stages implemented for the instruction (encode, decode, simulate); whether the compiler emits it for the validation corpus;');
P('the number of instances in programs whose bytes matched the reference assembler (sweeps, pseudoinstruction checks, and compiled programs);');
P('and the number of single-instruction cases that matched the reference emulator. Pseudoinstructions and aliases are checked through the real instructions they stand for.');
if (matrix.source) {
  P();
  P(`Validation run of the source tree with SHA-256 \`${matrix.source}\`.`);
}
P();
for (const b of availableBackends()) {
  const p = b.profile;
  const m = matrix.targets[p.id] ?? {};
  const real = b.instructions.filter((i) => !i.pseudo);
  const pseudo = b.instructions.filter((i) => i.pseudo);
  P(`## ${p.name}`);
  P();
  P(`${p.isa}. Not included: ${p.excluded.join('; ')}.`);
  P();
  P(`${real.length} instructions and ${pseudo.length} pseudoinstructions or aliases.`);
  P();
  P('| Instruction | Group | Format | Encode | Decode | Simulate | Emitted by the compiler | Assembler-checked instances | Emulator-checked cases | Defined in |');
  P('| --- | --- | --- | --- | --- | --- | --- | ---: | ---: | --- |');
  for (const i of real) {
    const e = m[i.mnemonic];
    P(`| \`${i.mnemonic}\` | ${i.group} | ${i.format} | ${yes(i.encode)} | ${yes(i.decode)} | ${yes(i.simulate)} | ${e ? yes(e.compilerGenerates) : 'n/a'} | ${e ? e.assemblerChecked.toLocaleString('en-US') : 'n/a'} | ${e ? e.emulatorChecked.toLocaleString('en-US') : 'n/a'} | ${i.reference} |`);
  }
  P();
  if (pseudo.length > 0) {
    P('| Pseudoinstruction or alias | Stands for |');
    P('| --- | --- |');
    for (const i of pseudo) P(`| \`${i.syntax}\` | ${(i.expansion ?? i.semantics).replace(/\|/g, '\\|')} |`);
    P();
  }
}
const out = join(root, 'docs', 'coverage.md');
if (process.argv.includes('--check')) {
  if (existsSync(out) && readFileSync(out, 'utf8').replace(/\r\n/g, '\n') === lines.join('\n')) console.log('docs/coverage.md is generated from the support matrix and the catalogs');
  else {
    console.log('docs/coverage.md is not the coverage tables of the support matrix and the catalogs; run node scripts/coverage-tables.ts');
    process.exitCode = 1;
  }
} else {
  writeFileSync(out, lines.join('\n'));
  console.log('docs/coverage.md written');
}
